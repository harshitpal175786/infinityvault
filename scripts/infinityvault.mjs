#!/usr/bin/env node

import { spawn, spawnSync } from 'node:child_process'
import { createInterface } from 'node:readline'
import { mkdir, readFile, writeFile, access, chmod } from 'node:fs/promises'
import { constants } from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const root = path.resolve(new URL('..', import.meta.url).pathname)
const backendDir = path.join(root, 'backend')
const frontendDir = path.join(root, 'frontend')
const venvPython = path.join(backendDir, '.venv', 'bin', 'python')
const defaultConfigPath = path.join(os.homedir(), '.config', 'infinityvault', '.env')

function printHelp() {
  console.log(`InfinityVault local launcher

Usage:
  npm run infinityvault -- setup       Configure Telegram and start both services
  npm run infinityvault -- start       Start both services using saved configuration
  npm run infinityvault -- faces       Install optional face recognition (CPU, ~400 MB)
  npm run infinityvault -- token       Generate the access token the API requires
  npm run infinityvault -- help        Show this help

Face recognition is optional. Run 'npm run infinityvault -- faces' once to
install it; the app works fully without it.

The setup command asks for Telegram application credentials only when they are
missing. Telegram phone, verification code, and optional 2FA are entered in
the browser's Connect Telegram flow and are never written to this config file.

Options:
  --config <path>    Use a different private env-file path
  --no-install       Do not create/install local dependencies
`)
}

function getOption(args, name) {
  const index = args.indexOf(name)
  if (index >= 0) return args[index + 1]
  const prefix = `${name}=`
  const value = args.find((arg) => arg.startsWith(prefix))
  return value?.slice(prefix.length)
}

function parseEnv(text) {
  const values = {}
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z][A-Z0-9_]*)\s*=\s*(.*)\s*$/)
    if (!match) continue
    values[match[1]] = match[2].replace(/^['"]|['"]$/g, '')
  }
  return values
}

function envText(values) {
  return [
    '# Managed by InfinityVault setup. Keep this file private.',
    '# Telegram application credentials from https://my.telegram.org/apps',
    `TELEGRAM_API_ID=${values.TELEGRAM_API_ID ?? ''}`,
    `TELEGRAM_API_HASH=${values.TELEGRAM_API_HASH ?? ''}`,
    '# Generated by the backend when it is first started unless provided here.',
    `TELEGRAM_SESSION_KEY=${values.TELEGRAM_SESSION_KEY ?? ''}`,
    '',
  ].join('\n')
}

async function readConfig(configPath) {
  try {
    return parseEnv(await readFile(configPath, 'utf8'))
  } catch (error) {
    if (error.code === 'ENOENT') return {}
    throw error
  }
}

function prompt(question) {
  const readline = createInterface({ input: process.stdin, output: process.stdout })
  return new Promise((resolve) => readline.question(question, (answer) => {
    readline.close()
    resolve(answer.trim())
  }))
}

function promptHidden(question) {
  if (!process.stdin.isTTY || !process.stdout.isTTY) return prompt(question)

  return new Promise((resolve, reject) => {
    const stdin = process.stdin
    let answer = ''
    process.stdout.write(question)
    stdin.setRawMode(true)
    stdin.resume()

    function cleanup() {
      stdin.setRawMode(false)
      stdin.pause()
      stdin.off('data', onData)
    }

    function finish(value) {
      cleanup()
      process.stdout.write('\n')
      resolve(value.trim())
    }

    function onData(chunk) {
      for (const character of chunk.toString()) {
        if (character === '\u0003') {
          cleanup()
          process.stdout.write('\n')
          reject(new Error('Setup cancelled'))
          return
        }
        if (character === '\r' || character === '\n') {
          finish(answer)
          return
        }
        if (character === '\u007f' || character === '\b') {
          answer = answer.slice(0, -1)
          continue
        }
        if (character >= ' ') answer += character
      }
    }

    stdin.on('data', onData)
  })
}

async function configureTelegram(configPath) {
  const values = await readConfig(configPath)
  if (values.TELEGRAM_API_ID && values.TELEGRAM_API_HASH) {
    console.log(`Using saved Telegram application credentials from ${configPath}`)
    return values
  }

  console.log('\nInfinityVault first-time setup')
  console.log('Telegram application credentials stay in a private file outside the repository.')
  console.log('Get them from https://my.telegram.org/apps.\n')

  let apiId = values.TELEGRAM_API_ID
  while (!apiId || !/^\d+$/.test(apiId)) {
    apiId = await prompt('Telegram API ID: ')
    if (!/^\d+$/.test(apiId)) console.log('API ID must contain numbers only.')
  }

  let apiHash = values.TELEGRAM_API_HASH
  while (!apiHash || !/^[a-f0-9]{32}$/i.test(apiHash)) {
    apiHash = await promptHidden('Telegram API hash (hidden): ')
    if (!/^[a-f0-9]{32}$/i.test(apiHash)) console.log('API hash must be the 32-character value from my.telegram.org.')
  }

  const nextValues = { ...values, TELEGRAM_API_ID: apiId, TELEGRAM_API_HASH: apiHash }
  await mkdir(path.dirname(configPath), { recursive: true, mode: 0o700 })
  await writeFile(configPath, envText(nextValues), { mode: 0o600 })
  await chmod(path.dirname(configPath), 0o700)
  await chmod(configPath, 0o600)
  console.log(`Saved private configuration to ${configPath}`)
  return nextValues
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd ?? root,
    stdio: 'inherit',
    env: { ...process.env, ...(options.env ?? {}) },
  })
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed`)
}

async function exists(filePath) {
  try {
    await access(filePath, constants.F_OK)
    return true
  } catch {
    return false
  }
}

async function prepareDependencies(skipInstall) {
  if (skipInstall) return

  if (!await exists(venvPython)) {
    console.log('\nCreating the backend Python environment…')
    run('python3', ['-m', 'venv', path.join(backendDir, '.venv')])
    run(venvPython, ['-m', 'pip', 'install', '-r', 'requirements.txt'], { cwd: backendDir })
  }

  if (!await exists(path.join(frontendDir, 'node_modules'))) {
    console.log('\nInstalling frontend dependencies…')
    run('npm', ['install'], { cwd: frontendDir })
  }
}

async function installFaceSupport() {
  if (!await exists(venvPython)) {
    console.log('\nCreating the backend Python environment…')
    run('python3', ['-m', 'venv', path.join(backendDir, '.venv')])
    run(venvPython, ['-m', 'pip', 'install', '-r', 'requirements.txt'], { cwd: backendDir })
  }
  console.log('\nInstalling optional face recognition packages (CPU build)…')
  console.log('This adds InsightFace, onnxruntime, OpenCV and NumPy.\n')
  run(venvPython, ['-m', 'pip', 'install', '-r', 'requirements-faces.txt'], { cwd: backendDir })
  console.log('\nFace recognition installed.')
  console.log('Start InfinityVault, then use People → Scan library.')
  console.log('The first scan downloads a ~160 MB model automatically.\n')
}

/**
 * Resolve the interface the API listens on.
 *
 * Loopback is the safe default. Listening on the network is only allowed when an
 * access token is configured, because an unsecured vault on a shared Wi-Fi is
 * readable by anyone on it. The token is the whole authorisation model, so the
 * two decisions are coupled rather than left to the caller to remember.
 */
async function resolveHost(configPath) {
  const requested = (process.env.INFINITYVAULT_HOST || '').trim()
  if (!requested) return { host: '127.0.0.1', reason: 'loopback (default)' }

  if (requested === '127.0.0.1' || requested === 'localhost') {
    return { host: '127.0.0.1', reason: 'loopback (requested)' }
  }

  let token = ''
  try {
    const contents = await readFile(configPath, 'utf8')
    const match = contents.match(/^INFINITYVAULT_ACCESS_TOKEN=(.+)$/m)
    token = match ? match[1].trim() : ''
  } catch {
    token = ''
  }

  if (!token) {
    console.error('\nRefusing to listen on ' + requested + ' without an access token.')
    console.error('That would expose your whole library to every device on this network.')
    console.error('Run  npm run infinityvault -- token  first, or unset INFINITYVAULT_HOST.\n')
    process.exit(1)
  }

  return { host: requested, reason: 'network, token required' }
}

async function startServices(configPath) {
  const children = []
  const { host, reason } = await resolveHost(configPath)
  if (host !== '127.0.0.1') {
    console.log(`\nAPI listening on ${host} (${reason}).`)
    console.log('Reach it from a phone at  http://<this-mac-ip>:8000\n')
  }
  const backend = spawn(venvPython, [
    '-m', 'uvicorn', 'app.main:app',
    '--host', host,
    '--port', '8000',
    '--env-file', configPath,
  ], { cwd: backendDir, stdio: 'inherit', env: process.env })
  const frontend = spawn('npm', ['run', 'dev', '--', '--host', '127.0.0.1'], {
    cwd: frontendDir,
    stdio: 'inherit',
    env: process.env,
  })
  children.push(backend, frontend)

  let stopping = false
  function stop() {
    if (stopping) return
    stopping = true
    for (const child of children) child.kill('SIGTERM')
  }

  process.on('SIGINT', stop)
  process.on('SIGTERM', stop)
  backend.on('exit', (code) => {
    if (!stopping && code !== 0) console.error(`Backend stopped with code ${code ?? 'unknown'}.`)
    if (!stopping) stop()
  })
  frontend.on('exit', (code) => {
    if (!stopping && code !== 0) console.error(`Frontend stopped with code ${code ?? 'unknown'}.`)
    if (!stopping) stop()
  })

  console.log('\nInfinityVault is running:')
  console.log('  Frontend: http://127.0.0.1:5173/')
  console.log('  Backend:  http://127.0.0.1:8000/')
  console.log('  Press Ctrl+C to stop both services.\n')
}

async function generateAccessToken(configPath) {
  const { randomBytes } = await import('node:crypto')
  const token = randomBytes(32).toString('base64url')
  const existing = await readConfig(configPath)
  existing.INFINITYVAULT_ACCESS_TOKEN = token

  await mkdir(path.dirname(configPath), { recursive: true })
  const body = Object.entries(existing)
    .map(([key, value]) => `${key}=${value}`)
    .join('\n')
  await writeFile(configPath, `${body}\n`, { mode: 0o600 })
  await chmod(configPath, 0o600)

  console.log('\nAccess token generated and saved to:')
  console.log(`  ${configPath}  (mode 0600)\n`)
  console.log('Restart the app, then paste this token when the browser asks:\n')
  console.log(`  ${token}\n`)
  console.log('Keep it private: anyone with this token can read your whole library.')
  console.log('Run this command again to rotate it.')
}

async function main() {
  const args = process.argv.slice(2)
  const command = args[0] ?? 'help'
  if (command === 'help' || command === '--help' || command === '-h') {
    printHelp()
    return
  }
  if (command === 'faces') {
    await installFaceSupport()
    return
  }
  if (command === 'token') {
    const configPath = path.resolve(getOption(args, '--config') ?? process.env.INFINITYVAULT_CONFIG ?? defaultConfigPath)
    await generateAccessToken(configPath)
    return
  }
  if (command !== 'setup' && command !== 'start') {
    printHelp()
    process.exitCode = 1
    return
  }

  if (Number(process.versions.node.split('.')[0]) < 18) {
    throw new Error('InfinityVault requires Node.js 18 or newer.')
  }

  const configPath = path.resolve(getOption(args, '--config') ?? process.env.INFINITYVAULT_CONFIG ?? defaultConfigPath)
  const skipInstall = args.includes('--no-install')
  const values = await readConfig(configPath)
  if (command === 'setup') await configureTelegram(configPath)
  else if (!values.TELEGRAM_API_ID || !values.TELEGRAM_API_HASH) {
    throw new Error(`Telegram credentials are missing. Run “npm run infinityvault -- setup” first.`)
  }

  await prepareDependencies(skipInstall)
  await startServices(configPath)
}

main().catch((error) => {
  console.error(`\nSetup failed: ${error.message}`)
  process.exitCode = 1
})
